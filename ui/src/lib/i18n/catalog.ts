export type MessageKey = keyof typeof en;

/** A catalog may be a partial draft; English fills every missing key. */
export type Catalog = Partial<Record<MessageKey, Message>>;

/** The English source catalog. Always available for fallback. */
export const englishCatalog: Catalog = en;

type CatalogLoader = () => Promise<{ default: Catalog }>;

/** Draft catalogs are code-split; English stays in the initial bundle. */
const CATALOG_LOADERS: Record<Exclude<LanguageId, 'en'>, CatalogLoader> = {
  id: () => import('./catalogs/id'),
  es: () => import('./catalogs/es'),
  fr: () => import('./catalogs/fr'),
  de: () => import('./catalogs/de'),
  ja: () => import('./catalogs/ja'),
  zh: () => import('./catalogs/zh'),
  ar: () => import('./catalogs/ar'),
  hi: () => import('./catalogs/hi'),
  ko: () => import('./catalogs/ko'),
  pt: () => import('./catalogs/pt'),
  ru: () => import('./catalogs/ru'),
  tr: () => import('./catalogs/tr'),
  vi: () => import('./catalogs/vi'),
};

const loaded = new Map<LanguageId, Catalog>([['en', en]]);

/** Load a catalog once. A failed chunk falls back to English, never blocks UI. */
export async function loadCatalog(language: LanguageId): Promise<Catalog> {
  const cached = loaded.get(language);
  if (cached) return cached;
  if (language === 'en') return en;
  try {
    const module = await CATALOG_LOADERS[language]();
    loaded.set(language, module.default);
    return module.default;
  } catch {
    return en;
  }
}

export function isCatalogLoaded(language: LanguageId): boolean {
  return loaded.has(language);
}

/** English is the source catalog; unloaded or draft keys fall back per key. */
export function translate(
  language: LanguageId,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const entry = loaded.get(language)?.[key] ?? en[key] ?? key;
  const merged = { ...BRAND_VARS, ...vars };
  const text = selectMessage(language, entry, merged);
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(merged, name) ? String(merged[name]) : match,
  );
}

/**
 * Pick the plural form for `vars.count`. Catalogs may provide only `other`
 * (languages such as Japanese), or `one`/`other` (English, Spanish). The
 * selected category comes from `Intl.PluralRules`, never from a hand-written
 * `count === 1` check.
 */
function selectMessage(
  language: LanguageId,
  entry: Message,
  vars?: Record<string, string | number>,
): string {
  if (typeof entry === 'string') return entry;
  const raw = vars?.count;
  const count = typeof raw === 'number' ? raw : Number(raw);
  if (!Number.isFinite(count)) return entry.other ?? entry.one ?? '';
  const category = new Intl.PluralRules(language).select(count);
  return entry[category] ?? entry.other ?? entry.one ?? '';
}
