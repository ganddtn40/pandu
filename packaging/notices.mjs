#!/usr/bin/env node
/**
 * Generate THIRD_PARTY_NOTICES.md from Cargo.lock and the UI lockfile.
 *
 *   node packaging/notices.mjs
 *   node packaging/notices.mjs --check
 *
 * Rust workspace crates are excluded: they are first-party. The UI's
 * devDependencies are included because Vite bundles them into the shipped
 * JavaScript. The Tauri CLI is a build tool and is not redistributed.
 */
import { execFileSync, execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const outPath = join(repoRoot, 'THIRD_PARTY_NOTICES.md');
const checkOnly = process.argv.includes('--check');

function run(command, args, options = {}) {
  return execFileSync(command, args, {
    cwd: repoRoot,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    ...options,
  });
}

const metadata = JSON.parse(run('cargo', ['metadata', '--format-version', '1', '--locked']));
const workspace = new Set(metadata.workspace_members);
const rust = metadata.packages
  .filter((pkg) => !workspace.has(pkg.id))
  .map((pkg) => ({
    name: pkg.name,
    version: pkg.version,
    license: pkg.license ?? (pkg.license_file ? `see ${pkg.license_file}` : 'NO LICENSE DECLARED'),
    source: pkg.repository ?? (pkg.source ? pkg.source.replace(/^registry\+/, '') : ''),
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

let js = [];
try {
  const licenses = JSON.parse(
    execSync('pnpm --dir ui licenses list --json', {
      cwd: repoRoot,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    }),
  );
  js = Object.values(licenses)
    .flat()
    .map((pkg) => ({
      name: pkg.name,
      version: (pkg.versions ?? []).join(', '),
      license: pkg.license ?? 'NO LICENSE DECLARED',
      source: pkg.homepage ?? '',
    }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
} catch (error) {
  console.warn(`pnpm licenses failed; JavaScript section will be empty: ${error.message}`);
}

const missing = [...rust, ...js].filter((pkg) => pkg.license === 'NO LICENSE DECLARED');

const lines = [
  '# Third-party notices',
  '',
  'This file is generated by `node packaging/notices.mjs`. It lists the',
  'third-party components distributed with the application. The full license',
  'text for each component is available from its source and in the lockfiles.',
  '',
  `- Rust crates: ${rust.length}`,
  `- JavaScript packages: ${js.length}`,
  '',
  '## Rust crates',
  '',
  '| Crate | Version | License | Source |',
  '| --- | --- | --- | --- |',
  ...rust.map((pkg) => `| \`${pkg.name}\` | ${pkg.version} | ${pkg.license} | ${pkg.source} |`),
  '',
  '## JavaScript packages',
  '',
  '| Package | Version | License | Source |',
  '| --- | --- | --- | --- |',
  ...js.map((pkg) => `| \`${pkg.name}\` | ${pkg.version} | ${pkg.license} | ${pkg.source} |`),
  '',
];

if (missing.length > 0) {
  lines.push('## Components without a declared license', '');
  for (const pkg of missing) lines.push(`- \`${pkg.name}\` ${pkg.version}`);
  lines.push('');
}

const text = `${lines.join('\n')}\n`;

if (checkOnly) {
  if (!existsSync(outPath)) {
    console.error('THIRD_PARTY_NOTICES.md is missing. Run: node packaging/notices.mjs');
    process.exit(1);
  }
  const current = readFileSync(outPath, 'utf8');
  if (current !== text) {
    console.error('THIRD_PARTY_NOTICES.md is stale. Run: node packaging/notices.mjs');
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES.md is current (${rust.length} crates, ${js.length} packages).`);
  if (missing.length > 0) {
    console.error(`${missing.length} component(s) declare no license.`);
    process.exit(1);
  }
  process.exit(0);
}

writeFileSync(outPath, text, 'utf8');
console.log(`wrote ${outPath} (${rust.length} crates, ${js.length} packages).`);
if (missing.length > 0) {
  console.error(`${missing.length} component(s) declare no license; resolve before release.`);
  process.exit(1);
}
